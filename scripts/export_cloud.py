"""Export everything the Cloudflare Worker needs from the Python source of truth.

Usage:  python scripts/export_cloud.py    (after build_index.py and build_vectors.py)

Writes, all derived and gitignored except the fixtures:
  worker/build/d1.sql             passages table + FTS5 index (same schema and tokenizer as keyword_index.py)
  worker/build/vectors.ndjson     one {"id", "values"} line per passage for `wrangler vectorize insert`
  worker/src/generated.ts         the system prompt, query instruction, stopwords, prices and document
                                  titles, copied from the Python modules so the demo cannot drift from
                                  what the evals measured
  eval/verify_cases.json          citation-check cases that the Python and TypeScript tests both run
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from cite_or_abstain import answer, ingest, keyword_index, models, retrieval  # noqa: E402

DEMO_MODEL = "claude-haiku-5-5"


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> int:
    passages = ingest.read_jsonl(ROOT / "data" / "passages.jsonl")
    build = ROOT / "worker" / "build"
    build.mkdir(parents=True, exist_ok=True)

    lines = [
        "DROP TABLE IF EXISTS passages_fts;", "DROP TABLE IF EXISTS passages;",
        "CREATE TABLE passages (rowid INTEGER PRIMARY KEY, id TEXT UNIQUE, doc TEXT, year INTEGER, page INTEGER, "
        "section TEXT, kind TEXT, text TEXT);",
        "CREATE VIRTUAL TABLE passages_fts USING fts5(section, text, content='passages', content_rowid='rowid', "
        "tokenize='porter unicode61');",
        "CREATE TABLE IF NOT EXISTS usage (day TEXT, ip_hash TEXT, count INTEGER, PRIMARY KEY (day, ip_hash));",
        "CREATE TABLE IF NOT EXISTS spend (id INTEGER PRIMARY KEY CHECK (id = 1), usd REAL NOT NULL);",
        "INSERT OR IGNORE INTO spend (id, usd) VALUES (1, 0);",
    ]
    for p in passages:
        lines.append("INSERT INTO passages (id, doc, year, page, section, kind, text) VALUES ("
                     f"{sql_str(p.id)}, {sql_str(p.doc)}, {p.year}, {p.page}, {sql_str(p.section)}, {sql_str(p.kind)}, {sql_str(p.text)});")
    lines.append("INSERT INTO passages_fts(passages_fts) VALUES ('rebuild');")
    (build / "d1.sql").write_text("\n".join(lines) + "\n", encoding="utf-8")

    vecs = np.load(ROOT / "data" / "vectors.npy")
    ids = json.loads((ROOT / "data" / "vector_ids.json").read_text(encoding="utf-8"))
    with (build / "vectors.ndjson").open("w", encoding="utf-8") as f:
        for pid, v in zip(ids, vecs):
            f.write(json.dumps({"id": pid, "values": [round(float(x), 6) for x in v]}) + "\n")

    import pymupdf
    manifest = json.loads((ROOT / "corpus" / "manifest.json").read_text(encoding="utf-8"))["files"]
    doc_urls = {}
    for name, entry in manifest.items():
        year = ingest.stated_year(pymupdf.open(ROOT / "corpus" / "raw" / name))
        doc_urls[ingest.doc_id(Path(name), year)] = entry["url"]

    gen = [
        "// Generated by scripts/export_cloud.py from the Python package. Do not edit by hand.",
        f"export const DOC_URLS: Record<string, string> = {json.dumps(doc_urls)};",
        f"export const SYSTEM = {json.dumps(answer.SYSTEM)};",
        f"export const CANARY = {json.dumps(answer.CANARY)};",
        f"export const QUERY_INSTRUCTION = {json.dumps(retrieval.QUERY_INSTRUCTION)};",
        f"export const STOPWORDS = new Set<string>({json.dumps(sorted(keyword_index.STOPWORDS))});",
        f"export const DOC_TITLES: Record<string, string> = {json.dumps(answer._DOC_TITLES)};",
        f"export const MIN_QUOTE_WORDS = {answer.MIN_QUOTE_WORDS};",
        f"export const MAX_QUOTE_WORDS = {answer.MAX_QUOTE_WORDS};",
        f"export const RRF_K = {retrieval.RRF_K};",
        f"export const FUSE_DEPTH = {retrieval.FUSE_DEPTH};",
        f"export const DEMO_MODEL = {json.dumps(DEMO_MODEL)};",
        f"export const PRICE_PER_MTOK = {json.dumps(dict(zip(('input', 'output'), models.PRICES[DEMO_MODEL])))};",
        f"export const ANSWER_SCHEMA = {json.dumps(models.ANSWER_SCHEMA)};",
    ]
    (ROOT / "worker" / "src").mkdir(parents=True, exist_ok=True)
    (ROOT / "worker" / "src" / "generated.ts").write_text("\n".join(gen) + "\n", encoding="utf-8")

    p = [{"id": "a", "text": "Single or Married filing separately $15,750 Married filing jointly 31,500"},
         {"id": "b", "text": "To qualify under the exclusive use test, you must use a specific area of your home only for your trade or business."}]
    reply = lambda cites, status="answered", text="x": {"status": status, "answer": text, "citations": cites}  # noqa: E731
    cases = [
        ("exact quote", reply([{"passage": 1, "quote": "Single or Married filing separately $15,750"}]), "answered"),
        ("curly quotes and double spaces", reply([{"passage": 2, "quote": "“To qualify under the  exclusive use test”"}]), "answered"),
        ("table pipes added by the model", reply([{"passage": 1, "quote": "| Married filing separately | $15,750"}]), "answered"),
        ("invented quote", reply([{"passage": 1, "quote": "Single filers get $16,000 this year"}]), "unverified"),
        ("passage number out of range", reply([{"passage": 7, "quote": "Single or Married filing separately $15,750"}]), "unverified"),
        ("one bad citation of two", reply([{"passage": 1, "quote": "Single or Married filing separately $15,750"},
                                           {"passage": 2, "quote": "and the garage counts too"}]), "unverified"),
        ("no citations", reply([]), "unverified"),
        ("quote too short", reply([{"passage": 1, "quote": "$15,750"}]), "unverified"),
        ("not found", reply([], status="not_found", text=""), "not_found"),
        ("empty answer", reply([{"passage": 1, "quote": "Single or Married filing separately $15,750"}], text=""), "unverified"),
    ]
    fixtures = {"passages": p, "cases": []}
    for name, rep, expected in cases:
        got = answer.verify(rep, p).status
        if got != expected:
            raise SystemExit(f"Python verify disagrees with fixture {name!r}: {got} != {expected}")
        fixtures["cases"].append({"name": name, "reply": rep, "expected": expected})
    (ROOT / "eval" / "verify_cases.json").write_text(json.dumps(fixtures, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"d1.sql: {len(passages):,} passages | vectors.ndjson: {len(ids):,} | generated.ts | verify_cases.json: {len(cases)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
